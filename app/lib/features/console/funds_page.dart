class FundsPage extends StatefulWidget {
  const FundsPage({super.key});

  @override
  State<FundsPage> createState() => _FundsPageState();
}

class _FundsPageState extends State<FundsPage> with LiveLoader<FundsPage, List<Fund>> {
  int _selected = 0;

  @override
  bool reloadOn(SseEvent event) => false;

  @override
  Future<List<Fund>> fetch(ApiClient api) async =>
      (await api.get('/api/staff/funds') as List).cast<Map<String, dynamic>>().map(Fund.new).toList();

  @override
  Widget build(BuildContext context) {
    return buildLoaded(context, (funds) {
      if (funds.isEmpty) return const EmptyState(icon: Icons.tune_rounded, title: 'No funds');
      final fund = funds[_selected.clamp(0, funds.length - 1)];
      return ListView(padding: const EdgeInsets.all(20), children: [
        const ConsolePageHeader(
          title: 'Fund settings',
          subtitle: 'Write your policy in plain language. Claude turns it into the rubric the AI caseworker applies.',
        ),
        Wrap(spacing: 8, children: [
          for (var i = 0; i < funds.length; i++)
            ChoiceChip(label: Text(funds[i].name), selected: i == _selected, onSelected: (_) => setState(() => _selected = i)),
        ]),
        const SizedBox(height: 16),
        _FundEditor(key: ValueKey(fund.id), fund: fund, onSaved: load),
      ]);
    });
  }
}

class _FundEditor extends StatefulWidget {
  const _FundEditor({super.key, required this.fund, required this.onSaved});
  final Fund fund;
  final VoidCallback onSaved;

  @override
  State<_FundEditor> createState() => _FundEditorState();
}

class _FundEditorState extends State<_FundEditor> {
  late final _policy = TextEditingController(text: widget.fund.raw['policyText'] as String? ?? '');
  late Map<String, dynamic> _rubric = Map<String, dynamic>.from(widget.fund.raw['rubric'] as Map? ?? {});
  late double _auto = widget.fund.autoApproveLimitCents / 100;
  late double _dual = ((widget.fund.raw['dualApprovalAboveCents'] as num?) ?? 50000) / 100;
  late bool _open = widget.fund.status == 'open';
  bool _compiling = false;
  bool _saving = false;
  bool _rubricChanged = false;

  @override
  void dispose() {
    _policy.dispose();
    super.dispose();
  }

  Future<void> _compile() async {
    setState(() => _compiling = true);
    try {
      final res = await AppScope.of(context).api.post('/api/staff/funds/${widget.fund.id}/compile-policy', body: {'policyText': _policy.text}) as Map<String, dynamic>;
      setState(() {
        _rubric = Map<String, dynamic>.from(res['rubric'] as Map);
        _rubricChanged = true;
      });
      if (mounted) showSnack(context, 'Rubric generated by ${res['model']}. Review it, then save.');
    } on ApiException catch (e) {
      if (mounted) showSnack(context, e.message, error: true);
    } finally {
      if (mounted) setState(() => _compiling = false);
    }
  }

  Future<void> _save() async {
    setState(() => _saving = true);
    try {
      await AppScope.of(context).api.put('/api/staff/funds/${widget.fund.id}', body: {
        'policyText': _policy.text,
        if (_rubricChanged) 'rubric': _rubric,
        'autoApproveLimitCents': (_auto * 100).round(),
        'dualApprovalAboveCents': (_dual * 100).round(),
        'status': _open ? 'open' : 'paused',
      });
      _rubricChanged = false;
      if (mounted) showSnack(context, 'Saved');
      widget.onSaved();
    } on ApiException catch (e) {
      if (mounted) showSnack(context, e.message, error: true);
    } finally {
      if (mounted) setState(() => _saving = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    final t = Theme.of(context).textTheme;
    final isAdmin = AppScope.of(context).session.user?.isAdmin == true;
    final categories = (_rubric['categories'] as List? ?? const []).cast<Map>();
    final criteria = (_rubric['criteria'] as List? ?? const []).cast<Map>();
    final maxGrant = ((_rubric['maxGrantCents'] as num?) ?? widget.fund.maxGrantCents).toDouble() / 100;

    final policyCard = SectionCard(
      title: 'Policy (plain language)',
      subtitle: 'What your fund covers and its rules, the way you\'d explain it to a volunteer.',
      child: Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
        TextField(controller: _policy, minLines: 10, maxLines: 22, enabled: isAdmin, style: t.bodyMedium),
        const SizedBox(height: 12),
        FilledButton.tonalIcon(
          onPressed: !isAdmin || _compiling ? null : _compile,
          icon: _compiling
              ? const SizedBox(width: 18, height: 18, child: CircularProgressIndicator(strokeWidth: 2))
              : const Icon(Icons.auto_awesome_rounded),
          label: Text(_compiling ? 'Claude is reading your policy…' : 'Generate rubric with AI'),
        ),
      ]),
    );

    final rubricCard = SectionCard(
      title: 'Rubric the AI applies',
      subtitle: _rubricChanged ? 'New draft, not saved yet.' : 'Currently in use.',
      trailing: _rubricChanged ? const Pill('Draft', color: T.warn, dense: true) : null,
      child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
        if (_rubric['summary'] is String) Text(_rubric['summary'] as String, style: t.bodyMedium?.copyWith(color: T.inkSoft)),
        const SizedBox(height: 12),
        Text('Categories', style: t.titleSmall),
        const SizedBox(height: 6),
        for (final c in categories)
          Padding(
            padding: const EdgeInsets.only(bottom: 6),
            child: Row(children: [
              const Icon(Icons.label_outline_rounded, size: 18, color: T.tealDark),
              const SizedBox(width: 8),
              Expanded(child: Text('${c['label']}', style: t.bodyMedium)),
              Text('≤ ${money(c['maxCents'] as num?, whole: true)}', style: t.bodySmall),
            ]),
          ),
        const SizedBox(height: 10),
        Text('Criteria', style: t.titleSmall),
        const SizedBox(height: 6),
        for (final c in criteria)
          Padding(
            padding: const EdgeInsets.only(bottom: 6),
            child: Row(crossAxisAlignment: CrossAxisAlignment.start, children: [
              Pill('${c['kind']}',
                  color: c['kind'] == 'disqualifying' ? T.danger : (c['kind'] == 'preferred' ? T.info : T.teal), dense: true),
              const SizedBox(width: 8),
              Expanded(child: Text('${c['text']}', style: t.bodyMedium)),
            ]),
          ),
        const SizedBox(height: 6),
        Text('Max grant ${money(maxGrant * 100, whole: true)} · cooldown ${_rubric['cooldownDays'] ?? 180} days', style: t.bodySmall),
      ]),
    );

    final rulesCard = SectionCard(
      title: 'Money rules',
      subtitle: 'Enforced in code, never by the AI.',
      child: Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
        SwitchListTile(
          contentPadding: EdgeInsets.zero,
          value: _open,
          onChanged: isAdmin ? (v) => setState(() => _open = v) : null,
          title: const Text('Accepting new requests'),
        ),
        const SizedBox(height: 8),
        Text('Auto-approve up to ${_auto == 0 ? 'off' : money(_auto * 100, whole: true)}', style: t.titleSmall),
        Text('Only when the AI recommends approval with ≥ 80% confidence, every automated check is clean, a document supports it, and the PayPal account is verified.',
            style: t.bodySmall),
        Slider(
          value: _auto.clamp(0, maxGrant),
          max: maxGrant,
          divisions: (maxGrant / 25).round().clamp(1, 100),
          label: _auto == 0 ? 'Off' : money(_auto * 100, whole: true),
          onChanged: isAdmin ? (v) => setState(() => _auto = v) : null,
        ),
        const SizedBox(height: 8),
        Text('Two reviewers required above ${money(_dual * 100, whole: true)}', style: t.titleSmall),
        Slider(
          value: _dual.clamp(0, maxGrant),
          max: maxGrant,
          divisions: (maxGrant / 25).round().clamp(1, 100),
          label: money(_dual * 100, whole: true),
          onChanged: isAdmin ? (v) => setState(() => _dual = v) : null,
        ),
        const SizedBox(height: 8),
        FilledButton(
          onPressed: !isAdmin || _saving ? null : _save,
          child: Text(_saving ? 'Saving…' : 'Save changes'),
        ),
        if (!isAdmin) Padding(padding: const EdgeInsets.only(top: 8), child: Text('Only admins can change fund settings.', style: t.bodySmall)),
      ]),
    );

    return LayoutBuilder(builder: (context, c) {
      if (c.maxWidth > 1000) {
        return Row(crossAxisAlignment: CrossAxisAlignment.start, children: [
          Expanded(flex: 3, child: Column(children: [policyCard, const SizedBox(height: 16), rubricCard])),
          const SizedBox(width: 16),
          Expanded(flex: 2, child: rulesCard),
        ]);
      }
      return Column(children: [policyCard, const SizedBox(height: 16), rulesCard, const SizedBox(height: 16), rubricCard]);
    });
  }
}
